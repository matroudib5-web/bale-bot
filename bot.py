#  🕐 نوبت خودکار — هر ۳۰ دقیقه
# ═══════════════════════════════════════════════════════════════
async def auto_turn_job(context: ContextTypes.DEFAULT_TYPE):
    """پردازش خودکار نوبت همه بازیکن‌ها"""
    if get_setting("season_ended") == "true":
        return

    cur = int(get_setting("current_turn", "1"))
    new_turn = cur + 1
    set_setting("current_turn", str(new_turn))

    players = get_active_players()
    for p in players:
        try:
            result = process_turn(p["user_id"])
            if not result:
                continue

            text = (
                f"📅 *نوبت {new_turn}*\n"
                f"━━━━━━━━━━━━━━━━━━━━━━\n"
                f"🗓️ {result['date_pretty']}\n"
            )
            if result["events"]:
                text += "\n📰 *رویدادها:*\n"
                for e in result["events"]:
                    text += f"• {e}\n"
            if result["completed"]:
                text += "\n✅ *تکمیل‌شده:*\n"
                for c in result["completed"][:5]:
                    text += f"• {c}\n"
            if result["protests"]:
                text += "\n🔥 *اعتراض:*\n"
                for pr in result["protests"]:
                    text += f"• {pr}\n"

            await context.bot.send_message(
                p["user_id"], text,
                parse_mode="Markdown",
                reply_markup=main_menu_reply())
        except Exception as e:
            log.warning(f"خطا در نوبت {p['user_id']}: {e}")

    # خبر سرگرمی رندوم
    if new_turn % 5 == 0:
        news = generate_random_news(new_turn)
        if news:
            try:
                await context.bot.send_message(NEWS_CHANNEL,
                    f"📰 {news}", parse_mode="Markdown")
            except Exception: pass

    # سازمان ملل
    if new_turn % UN_INTERVAL == 0:
        await start_un_session(context, new_turn)


