def init_db():
    conn = sqlite3.connect(DB_FILE)
    c = conn.cursor()

    # 1. players — بازیکن‌های اصلی
    c.execute("""
        CREATE TABLE IF NOT EXISTS players (
            user_id     INTEGER PRIMARY KEY,
            country     TEXT UNIQUE,
            gov         TEXT DEFAULT 'parliamentary_republic',
            is_vip      INTEGER DEFAULT 0,
            created_at  TEXT
        )
    """)

    # 2. country_state — وضعیت لحظه‌ای کشور
    c.execute("""
        CREATE TABLE IF NOT EXISTS country_state (
            user_id     INTEGER PRIMARY KEY,
            turn        INTEGER DEFAULT 1,
            game_date   TEXT DEFAULT '1939-09-01',
            money       REAL DEFAULT 0,
            food        REAL DEFAULT 0,
            water       REAL DEFAULT 0,
            steel       REAL DEFAULT 0,
            oil         REAL DEFAULT 0,
            coal        REAL DEFAULT 0,
            manpower    REAL DEFAULT 0,
            equipments  REAL DEFAULT 0,
            tax_rate    INTEGER DEFAULT 20,
            happiness   INTEGER DEFAULT 70,
            unrest      INTEGER DEFAULT 0,
            surveillance INTEGER DEFAULT 20,
            protest_active INTEGER DEFAULT 0,
            protest_turns_left INTEGER DEFAULT 0,
            protest_speech_done INTEGER DEFAULT 0,
            suppress_cooldown INTEGER DEFAULT 0,
            suppress_count INTEGER DEFAULT 0,
            neglect_strikes INTEGER DEFAULT 0,
            last_turn_time TEXT,
            last_action_turn INTEGER DEFAULT 1,
            war_active  INTEGER DEFAULT 0,
            atomic_stage INTEGER DEFAULT 0,
            atomic_ready INTEGER DEFAULT 0,
            last_collection TEXT,
            FOREIGN KEY (user_id) REFERENCES players(user_id)
        )
    """)

    # 3. army_units — واحدهای ارتش
    c.execute("""
        CREATE TABLE IF NOT EXISTS army_units (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            category    TEXT,
            model_name  TEXT,
            count       INTEGER DEFAULT 0,
            crew_per_unit INTEGER DEFAULT 1,
            power       INTEGER DEFAULT 0,
            UNIQUE(user_id, category, model_name)
        )
    """)

    # 4. crew — خدمه
    c.execute("""
        CREATE TABLE IF NOT EXISTS crew (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            crew_type   TEXT,
            count       INTEGER DEFAULT 0,
            UNIQUE(user_id, crew_type)
        )
    """)

    # 5. equipment — تجهیزات
    c.execute("""
        CREATE TABLE IF NOT EXISTS equipment (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            eq_type     TEXT,
            count       INTEGER DEFAULT 0,
            UNIQUE(user_id, eq_type)
        )
    """)

    # 6. factories — کارخونه‌ها
    c.execute("""
        CREATE TABLE IF NOT EXISTS factories (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            factory_key TEXT,
            level       INTEGER DEFAULT 1,
            workers     INTEGER DEFAULT 0,
            max_workers INTEGER DEFAULT 50,
            active      INTEGER DEFAULT 1,
            UNIQUE(user_id, factory_key)
        )
    """)

    # 7. research_progress — تحقیقات انجام‌شده
    c.execute("""
        CREATE TABLE IF NOT EXISTS research_progress (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            category    TEXT,
            model_name  TEXT,
            done        INTEGER DEFAULT 0,
            UNIQUE(user_id, category, model_name)
        )
    """)

    # 8. production_queue — صف تولید
    c.execute("""
        CREATE TABLE IF NOT EXISTS production_queue (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            kind        TEXT,
            item_key    TEXT,
            quantity    INTEGER DEFAULT 0,
            turns_left  INTEGER DEFAULT 0,
            created_turn INTEGER,
            UNIQUE(user_id, kind, item_key)
        )
    """)

    # 9. project_queue — صف پروژه‌ها
    c.execute("""
        CREATE TABLE IF NOT EXISTS project_queue (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            project_key TEXT UNIQUE,
            turns_left  INTEGER DEFAULT 0,
            created_turn INTEGER
        )
    """)

    # 10. completed_projects — پروژه‌های تکمیل‌شده
    c.execute("""
        CREATE TABLE IF NOT EXISTS completed_projects (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            project_key TEXT,
            done_turn   INTEGER,
            UNIQUE(user_id, project_key)
        )
    """)

    # 11. spy_missions — ماموریت‌های جاسوسی
    c.execute("""
        CREATE TABLE IF NOT EXISTS spy_missions (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            from_uid    INTEGER,
            to_uid      INTEGER,
            turns_left  INTEGER DEFAULT 0,
            created_turn INTEGER,
            status      TEXT DEFAULT 'pending'
        )
    """)

    # 12. wars — جنگ‌ها
    c.execute("""
        CREATE TABLE IF NOT EXISTS wars (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            attacker    TEXT,
            defender    TEXT,
            status      TEXT DEFAULT 'declared',
            created_turn INTEGER,
            UNIQUE(attacker, defender)
        )
    """)

    # 13. war_fronts — جبهه‌ها
    c.execute("""
        CREATE TABLE IF NOT EXISTS war_fronts (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            war_id      INTEGER,
            attacker_uid INTEGER,
            defender_uid INTEGER,
            attacker_force TEXT,
            defender_force TEXT,
            stage       TEXT DEFAULT 'moving',
            turns_left  INTEGER DEFAULT 1,
            created_turn INTEGER
        )
    """)

    # 14. negotiations — مذاکرات و درخواست‌ها
    c.execute("""
        CREATE TABLE IF NOT EXISTS negotiations (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            from_uid    INTEGER,
            to_uid      INTEGER,
            kind        TEXT,
            payload     TEXT,
            status      TEXT DEFAULT 'pending',
            created_turn INTEGER
        )
    """)

    # 15. trades — تجارت
    c.execute("""
        CREATE TABLE IF NOT EXISTS trades (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            from_uid    INTEGER,
            to_uid      INTEGER,
            give_res    TEXT,
            give_amt    INTEGER,
            give_model  TEXT,
            want_res    TEXT,
            want_amt    INTEGER,
            want_model  TEXT,
            status      TEXT DEFAULT 'pending',
            created_turn INTEGER
        )
    """)

    # 16. nap — پیمان عدم تعرض
    c.execute("""
        CREATE TABLE IF NOT EXISTS nap (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            a_uid       INTEGER,
            b_uid       INTEGER,
            until_turn  INTEGER,
            UNIQUE(a_uid, b_uid)
        )
    """)

    # 17. border_access — قرارداد مرزی
    c.execute("""
        CREATE TABLE IF NOT EXISTS border_access (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            a_uid       INTEGER,
            b_uid       INTEGER,
            UNIQUE(a_uid, b_uid)
        )
    """)

    # 18. news_feed — خبرهای کانال
    c.execute("""
        CREATE TABLE IF NOT EXISTS news_feed (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            turn        INTEGER,
            category    TEXT,
            text        TEXT,
            created_at  TEXT
        )
    """)

    # 19. settings — تنظیمات جهانی
    c.execute("""
        CREATE TABLE IF NOT EXISTS settings (
            key TEXT PRIMARY KEY,
            value TEXT
        )
    """)

    # 20. used_items — آیتم‌های استفاده‌شده
    c.execute("""
        CREATE TABLE IF NOT EXISTS used_items (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id     INTEGER,
            item_key    TEXT,
            target_uid  INTEGER,
            used_turn   INTEGER,
            turns_left  INTEGER DEFAULT 0
        )
    """)

    # 21. atomic_program — برنامه اتمی هر کشور
    c.execute("""
        CREATE TABLE IF NOT EXISTS atomic_program (
            user_id     INTEGER PRIMARY KEY,
            stage       INTEGER DEFAULT 0,
            bombs       INTEGER DEFAULT 0,
            turns_left  INTEGER DEFAULT 0
        )
    """)

    # 22. global_state — وضعیت جهانی
    c.execute("""
        CREATE TABLE IF NOT EXISTS global_state (
            key TEXT PRIMARY KEY,
            value TEXT
        )
    """)

    # مقدارهای اولیه
    c.execute("INSERT OR IGNORE INTO global_state (key, value) VALUES ('atomic_used', 'false')")
    c.execute("INSERT OR IGNORE INTO global_state (key, value) VALUES ('current_turn', '1')")
    c.execute("INSERT OR IGNORE INTO global_state (key, value) VALUES ('un_session_active', 'false')")
    c.execute("INSERT OR IGNORE INTO global_state (key, value) VALUES ('season_ended', 'false')")

    conn.commit()
    conn.close()


