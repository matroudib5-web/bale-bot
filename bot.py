async def on_attack_go(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    uid = update.effective_user.id
    state = get_state(uid)
    target_key = ctx.user_data.get("attack_target")
    if not target_key:
        await update.message.reply_text("❌ هدف انتخاب نشده."); return
    target_uid = find_player_by_country(target_key)
    if not target_uid:
        await update.message.reply_text("❌ بازیکن نداره."); return

    can, way = can_attack(state["country"], target_key, uid, target_uid)
    if not can:
        await update.message.reply_text(f"❌ {way}"); return

    # هزینه حمله
    attack_cost_money = 1000
    attack_cost_oil = 50
    attack_cost_food = 200
    if state["money"] < attack_cost_money or state["oil"] < attack_cost_oil or state["food"] < attack_cost_food:
        await update.message.reply_text(
            f"❌ منابع کافی نداری!\n"
            f"نیاز: {attack_cost_money}💰 + {attack_cost_oil}🛢️ + {attack_cost_food}🍞"
        ); return

    save_state(uid, money=state["money"]-attack_cost_money,
        oil=state["oil"]-attack_cost_oil, food=state["food"]-attack_cost_food,
        war_active=1)

    # نبرد
    my_atk = compute_army_power(uid, "attack")
    enemy_def = compute_army_power(target_uid, "defense")

    target_state = get_state(target_uid)
    c = COUNTRIES[target_key]

    add_news(state["turn"], "war",
        f"⚔️ {COUNTRIES[state['country']]['name']} به {c['name']} حمله کرد!")
    speech = f"رهبر {COUNTRIES[state['country']]['name']} در سخنرانی خود گفت: «{c['name']} پاسخگوی این تجاوز خواهد بود.»"
    add_news(state["turn"], "speech", speech)

    if my_atk > enemy_def:
        # پیروزی
        ratio = my_atk / max(1, enemy_def)
        loss_pct = max(0.05, min(0.5, 0.3 / ratio))

        # تلفات
        units = get_army(uid)
        conn = db()
        for u in units:
            new_count = int(u["count"] * (1 - loss_pct * random.uniform(0.5, 1.5)))
            new_count = max(0, new_count)
            conn.execute("UPDATE army_units SET count=? WHERE id=?", (new_count, u["id"]))
        # خدمه: هر واحد از دست رفته → خدمه هم می‌ره
        # ساده: ۵٪ کل خدمه
        # می‌شه بعداً دقیق‌تر کرد
        conn.commit(); conn.close()

        result = (
            f"🏆 *پیروزی!*\n\n"
            f"هدف: {c['flag']} {c['name']}\n"
            f"قدرت حمله: {fmt(my_atk)}\n"
            f"دفاع دشمن: {fmt(enemy_def)}\n\n"
            f"تلفات: ~{int(loss_pct*100)}%"
        )
        add_news(state["turn"], "battle", result)
        try:
            await ctx.bot.send_message(target_uid,
                f"💀 *{COUNTRIES[state['country']]['name']} به تو حمله کرد و پیروز شد!*",
                parse_mode="Markdown")
        except Exception: pass
    else:
        # شکست
        loss_pct = random.uniform(0.3, 0.6)
        units = get_army(uid)
        conn = db()
        for u in units:
            new_count = int(u["count"] * (1 - loss_pct))
            conn.execute("UPDATE army_units SET count=? WHERE id=?", (new_count, u["id"]))
        conn.commit(); conn.close()

        result = (
            f"💀 *شکست!*\n\n"
            f"هدف: {c['flag']} {c['name']}\n"
            f"قدرت حمله: {fmt(my_atk)}\n"
            f"دفاع دشمن: {fmt(enemy_def)}\n\n"
            f"تلفات: ~{int(loss_pct*100)}%"
        )
        add_news(state["turn"], "battle", result)
        try:
            await ctx.bot.send_message(target_uid,
                f"🏆 *{COUNTRIES[state['country']]['name']} به تو حمله کرد و شکست خورد!*",
                parse_mode="Markdown")
        except Exception: pass

    ctx.user_data["attack_target"] = None
    await update.message.reply_text(result, reply_markup=main_menu_reply(), parse_mode="Markdown")


