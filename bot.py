def get_neighbors(country_key):
    return COUNTRIES.get(country_key, {}).get("neighbors", [])


def has_sea_access(country_key):
    return COUNTRIES.get(country_key, {}).get("has_sea", False)


def can_attack(from_key, to_key, from_uid=None, to_uid=None):
    """بررسی مسیر حمله"""
    if from_key == to_key:
        return False, "نمی‌توانی به خودت حمله کنی"

    neighbors = get_neighbors(from_key)
    if to_key in neighbors:
        return True, "زمینی"

    # قرارداد مرزی
    if from_uid and to_uid:
        for n_key in neighbors:
            n_uid = find_player_by_country(n_key)
            if n_uid and get_border_access(from_uid, n_uid):
                # فقط اگه مقصد هم همسایه‌ی اون کشور میانی باشه
                if to_key in get_neighbors(n_key):
                    return True, f"مرزی از {COUNTRIES[n_key]['name']}"

    # دریایی
    if has_sea_access(from_key) and has_sea_access(to_key):
        return True, "دریایی"

    return False, "راهی برای حمله نداری"


def get_distance_multiplier(from_key, to_key):
    if to_key in get_neighbors(from_key):
        return 1.0
    if has_sea_access(from_key) and has_sea_access(to_key):
        return 2.0
    return 1.5


