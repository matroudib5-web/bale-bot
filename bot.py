def get_state(user_id):
    """وضعیت کامل کشور — ترکیب players و country_state"""
    conn = db()
    p = conn.execute("SELECT * FROM players WHERE user_id=?", (user_id,)).fetchone()
    s = conn.execute("SELECT * FROM country_state WHERE user_id=?", (user_id,)).fetchone()
    conn.close()
    if not p or not s:
        return None
    result = dict(p)
    result.update(dict(s))
    return result


def save_state(user_id, **fields):
    """ذخیره در country_state"""
    if not fields:
        return
    valid = ["turn", "game_date", "money", "food", "water", "steel", "oil", "coal",
             "manpower", "equipments", "tax_rate", "happiness", "unrest",
             "surveillance", "protest_active", "protest_turns_left",
             "protest_speech_done", "suppress_cooldown", "suppress_count",
             "neglect_strikes", "last_turn_time", "last_action_turn", "war_active",
             "atomic_stage", "atomic_ready", "last_collection"]
    updates = {k: v for k, v in fields.items() if k in valid}
    if not updates:
        return
    cols = ", ".join(f"{k}=?" for k in updates)
    vals = list(updates.values()) + [user_id]
    conn = db()
    conn.execute(f"UPDATE country_state SET {cols} WHERE user_id=?", vals)
    conn.commit()
    conn.close()


