async def on_hire_worker_input(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    if ctx.user_data.get("waiting") != "hire_worker": return False
    try:
        qty = int(update.message.text.strip())
        if qty <= 0: raise ValueError
    except Exception:
        await update.message.reply_text("❌ فرمت نامعتبر!"); return True
    uid = update.effective_user.id
    factories = get_factories(uid)
    free = 0
    for f in factories:
        free += f["max_workers"] - f["workers"]
    if qty > free:
        await update.message.reply_text(
            f"❌ ظرفیت کافی نداری!\n"
            f"ظرفیت آزاد: {free}\n"
            f"برای ظرفیت بیشتر، کارخونه ارتقا بده."
        ); ctx.user_data["waiting"] = None; return True

    # کارگرها بین کارخونه‌ها پخش می‌شن
    remaining = qty
    conn = db()
    for f in factories:
        if remaining <= 0: break
        free_here = f["max_workers"] - f["workers"]
        add = min(free_here, remaining)
        if add > 0:
            conn.execute("UPDATE factories SET workers = workers + ? WHERE id=?", (add, f["id"]))
            remaining -= add
    conn.commit(); conn.close()
    ctx.user_data["waiting"] = None
    await update.message.reply_text(f"✅ {qty} کارگر استخدام شد!",
        reply_markup=main_menu_reply())
    return True


