def compute_happiness_delta(user_id, state):
    """دلتای رضایت در این نوبت"""
    delta = 0
    details = []

    # مالیات
    tax = state.get("tax_rate", 20)
    if tax > 35:
        delta -= 5
        details.append(f"💵 مالیات بالا: -5")
    elif tax > 25:
        delta -= 2
        details.append(f"💵 مالیات: -2")
    elif tax < 10:
        delta += 3
        details.append(f"💵 مالیات کم: +3")
    elif tax < 15:
        delta += 1
        details.append(f"💵 مالیات: +1")

    # غذا
    food = state.get("food", 0)
    if food < 100:
        delta -= 5
        details.append(f"🍞 کمبود غذا: -5")
    elif food < 300:
        delta -= 2
        details.append(f"🍞 غذای کم: -2")
    elif food > 2000:
        delta += 1
        details.append(f"🍞 غذای فراوان: +1")

    # آب
    water = state.get("water", 0)
    if water < 50:
        delta -= 4
        details.append(f"💧 کمبود آب: -4")
    elif water > 1000:
        delta += 1

    # جنگ
    if state.get("war_active"):
        delta -= 2
        details.append(f"⚔️ جنگ: -2")

    # نظارت بر مردم
    surv = state.get("surveillance", 20)
    delta -= surv // 20
    if surv > 40:
        details.append(f"🕵️ نظارت: -{surv//20}")

    # سرکوب کول‌داون
    if state.get("suppress_cooldown", 0) > 0:
        delta -= 1

    # کارگرها (حقوق و تعداد)
    factories = get_factories(user_id)
    total_workers = sum(f["workers"] for f in factories)
    if total_workers > 100:
        delta -= total_workers // 200
        details.append(f"👷 کارگر زیاد: -{total_workers//200}")

    # پروژه‌های رفاهی
    completed = get_completed_projects(user_id)
    for p_key in completed:
        p = PROJECTS.get(p_key, {})
        if p.get("effect") == "happiness":
            delta += p.get("value", 0) // 3
            details.append(f"🏥 {p['name']}: +{p.get('value',0)//3}")

    # خدمت اجباری
    if "conscription" in completed:
        delta -= 2
        details.append("📋 خدمت اجباری: -2")

    # بی‌کاری (تولید صفر)
    if state.get("money", 0) <= 0:
        delta -= 3
        details.append("💰 بی‌پولی: -3")

    # حکومت
    gov = state.get("gov", "parliamentary_republic")
    gov_data = GOVERNMENTS.get(gov, {})
    gov_mod = gov_data.get("happiness_mod", 0)
    delta += gov_mod
    if gov_mod != 0:
        details.append(f"🏛️ حکومت: {gov_mod:+}")

    # VIP
    if is_vip(user_id) and delta < 0:
        delta = int(delta / 2)

    return delta, details


