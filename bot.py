async def is_user_member(ctx, username, user_id):
    try:
        member = await ctx.bot.get_chat_member(chat_id=username, user_id=user_id)
        if member.status in (ChatMemberStatus.MEMBER, ChatMemberStatus.ADMINISTRATOR, ChatMemberStatus.OWNER):
            return True
        return False
    except Exception as e:
        log.warning(f"عضویت {username}: {e}")
        return False


