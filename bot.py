def process_suppression(user_id, state):
    """پردازش سرکوب‌های قدیمی"""
    cd = state.get("suppress_cooldown", 0)
    if cd > 0:
        cd -= 1
        updates = {"suppress_cooldown": cd}
        if cd == 0:
            # عوارض بلندمدت
            updates["happiness"] = max(0, state.get("happiness", 70) - 5)
        return updates
    return {}


