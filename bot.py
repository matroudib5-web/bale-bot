def process_turn(user_id):
    state = get_state(user_id)
    if not state:
        return None

    country = COUNTRIES[state["country"]]
    is_vip_player = is_vip(user_id)
    turn = state["turn"] + 1

    updates = {}
    messages = {"events": [], "produced": [], "completed": [], "wars": [], "protests": []}

    # ═══ ۱. مالیات و درآمد پایه ═══
    tax = state.get("tax_rate", 20)
    base_income = country["money"] / 10  # درآمد پایه
    tax_mult = tax / 20.0
    income = base_income * tax_mult
    if is_vip_player:
        income *= 2
    updates["money"] = state.get("money", 0) + income

    # ═══ ۲. غذا و آب ═══
    food_income = country["food"] / 20
    if is_vip_player:
        food_income *= 2
    updates["food"] = state.get("food", 0) + food_income

    water_income = country["food"] / 25
    updates["water"] = state.get("water", 0) + water_income

    # ═══ ۳. کارخونه‌ها ═══
    salary, prod = process_factories(user_id, state)
    for res, amt in prod.items():
        if is_vip_player:
            amt *= 2
        updates[res] = updates.get(res, state.get(res, 0)) + amt
    updates["money"] -= salary

    # ═══ ۴. استخراج پایه ═══
    updates["steel"] = updates.get("steel", state.get("steel", 0)) + country["steel"] / 50
    updates["oil"] = updates.get("oil", state.get("oil", 0)) + country["oil"] / 50
    updates["coal"] = updates.get("coal", state.get("coal", 0)) + country["coal"] / 50

    # ═══ ۵. تدارکات ارتش ═══
    units = get_army(user_id)
    supply_cost = {"money": 0, "food": 0, "oil": 0, "water": 0}
    total_units = 0
    for u in units:
        cat = u["category"]
        cnt = u["count"]
        total_units += cnt
        if cat == "tanks":
            s = SUPPLY["tank"]
        elif cat in ("fighters", "jets", "bombers"):
            s = SUPPLY["plane"]
        elif cat == "ships":
            s = SUPPLY["ship"]
        else:
            continue
        for k in supply_cost:
            supply_cost[k] += s.get(k, 0) * cnt

    soldiers = state.get("soldiers", 0)
    s = SUPPLY["soldier"]
    for k in supply_cost:
        supply_cost[k] += s.get(k, 0) * soldiers

    for k, v in supply_cost.items():
        updates[k] = max(0, updates.get(k, state.get(k, 0)) - v)

    # ═══ ۶. صف تولید ═══
    queue = get_production_queue(user_id)
    conn = db()
    for item in queue:
        turns = item["turns_left"] - 1
        if turns <= 0:
            # تکمیل شد
            category = item["kind"]
            model = item["item_key"]
            qty = item["quantity"]
            if category == "crew":
                add_crew(user_id, model, qty)
            elif category == "equipment":
                add_equipment(user_id, model, qty)
            else:
                # پیدا کردن قدرت مدل
                tree = get_country_research(state["country"], category)
                power, crew_per = 0, 1
                for name, pw, _, _, _, _, cp, _, _ in tree:
                    if name == model:
                        power = pw
                        crew_per = cp
                        break
                add_army_unit(user_id, category, model, qty, crew_per, power)
            conn.execute("DELETE FROM production_queue WHERE id=?", (item["id"],))
            messages["completed"].append(f"{qty} × {model}")
        else:
            conn.execute("UPDATE production_queue SET turns_left=? WHERE id=?", (turns, item["id"]))
    conn.commit()
    conn.close()

    # ═══ ۷. صف پروژه ═══
    projects = get_project_queue(user_id)
    conn = db()
    for p in projects:
        turns = p["turns_left"] - 1
        if turns <= 0:
            mark_project_completed(user_id, p["project_key"])
            conn.execute("DELETE FROM project_queue WHERE id=?", (p["id"],))
            p_info = PROJECTS.get(p["project_key"], {})
            messages["completed"].append(f"🏗️ {p_info.get('name', p['project_key'])}")
        else:
            conn.execute("UPDATE project_queue SET turns_left=? WHERE id=?", (turns, p["id"]))
    conn.commit()
    conn.close()

    # ═══ ۸. جاسوسی ═══
    spy_missions = get_spy_missions(user_id)
    for m in spy_missions:
        turns = m["turns_left"] - 1
        if turns <= 0:
            # انجام
            result = resolve_spy(m["from_uid"], m["to_uid"])
            messages["completed"].append(f"🕵️ ماموریت جاسوسی: {result}")
            conn = db()
            conn.execute("UPDATE spy_missions SET status='done' WHERE id=?", (m["id"],))
            conn.commit()
            conn.close()
        else:
            conn = db()
            conn.execute("UPDATE spy_missions SET turns_left=? WHERE id=?", (turns, m["id"]))
            conn.commit()
            conn.close()

    # ═══ ۹. رضایت ═══
    delta, details = compute_happiness_delta(user_id, state)
    new_happiness = max(0, min(100, state.get("happiness", 70) + delta))
    updates["happiness"] = new_happiness
    updates["unrest"] = 100 - new_happiness

    # ═══ ۱۰. اعتراض ═══
    protest = process_protest(user_id, state)
    if protest.get("started"):
        updates.update(protest["updates"])
        messages["protests"].append(protest["speech"])
        # خبر
        c = COUNTRIES[state["country"]]
        add_news(turn, "protest", f"🔥 اعتراض در {c['name']} شروع شد!")
        add_news(turn, "speech", protest["speech"])
    elif protest.get("ended"):
        updates.update(protest["updates"])
        c = COUNTRIES[state["country"]]
        add_news(turn, "protest", f"✅ اعتراض در {c['name']} پایان یافت.")
    elif protest.get("updates"):
        updates.update(protest["updates"])

    # ═══ ۱۱. سرکوب ═══
    sup_updates = process_suppression(user_id, state)
    updates.update(sup_updates)

    # ═══ ۱۲. امور کشور رهاشده ═══
    last_action = state.get("last_action_turn", 1)
    if turn - last_action >= 5:
        updates["neglect_strikes"] = (state.get("neglect_strikes", 0) + 1)
        if state.get("neglect_strikes", 0) >= 3:
            updates["happiness"] = max(0, updates.get("happiness", new_happiness) - 5)
            messages["events"].append("⚠️ امور کشور رها شده — رضایت -5")

    # ═══ ۱۳. تاریخ ═══
    new_date = advance_game_date(state["game_date"], GAME_DAYS_PER_TURN)
    updates["game_date"] = new_date
    updates["turn"] = turn
    updates["last_turn_time"] = datetime.utcnow().isoformat()

    # رویداد تاریخی؟
    ev = get_events_for_date(new_date)
    if ev:
        messages["events"].append(ev)
        add_news(turn, "historical", ev)

    # ═══ ۱۴. پایان سیزن ═══
    if turn >= TOTAL_TURNS:
        set_setting("season_ended", "true")
        messages["events"].append("🏁 سیزن به پایان رسید!")

    # ═══ ۱۵. اتفاق اتم ═══
    if turn == ATOMIC_UNLOCK_TURN:
        add_news(turn, "atomic", "☢️ پروژه منهتن برای آلمان و آمریکا باز شد!")

    # ═══ ۱۶. ذخیره ═══
    save_state(user_id, **updates)

    return {
        "turn": turn,
        "date": new_date,
        "date_pretty": format_game_date(parse_game_date(new_date)),
        "events": messages["events"],
        "completed": messages["completed"],
        "protests": messages["protests"],
    }


