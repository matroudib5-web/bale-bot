#  🕵️ حل ماموریت جاسوسی
# ═══════════════════════════════════════════════════════════════
def resolve_spy(from_uid, to_uid):
    """نتیجه ماموریت جاسوسی"""
    from_state = get_state(from_uid)
    to_state = get_state(to_uid)
    if not from_state or not to_state:
        return "❌ خطا"

    # اگه to_admin باشه (یکی از اون ۲ نفر)
    if to_uid in ADMIN_IDS:
        # میانگین با یه کشور رندوم
        random_players = [p for p in get_active_players() if p["user_id"] not in ADMIN_IDS]
        if random_players:
            rand_p = random.choice(random_players)
            rand_state = get_state(rand_p["user_id"])
            if rand_state:
                avg_money = (to_state.get("money", 0) + rand_state.get("money", 0)) / 2
                avg_steel = (to_state.get("steel", 0) + rand_state.get("steel", 0)) / 2
                # شانس موفقیت ۳۰٪
                if random.random() < 0.30:
                    return (f"✅ موفق! (تخمین میانگین با کشور رندوم)\n"
                            f"💰 {int(avg_money)}\n⚙️ {int(avg_steel)}")
                return "🚨 لو رفت!"

    # شانس پایه ۶۰٪، کاهش با نظارت
    surv = to_state.get("surveillance", 20)
    chance = 0.60 - (surv / 100) * 0.5  # نظارت ۱۰۰٪ → شانس ۱۰٪
    if random.random() < chance:
        return (f"✅ موفق!\n"
                f"💰 {int(to_state.get('money', 0))}\n"
                f"⚙️ {int(to_state.get('steel', 0))}\n"
                f"🛢️ {int(to_state.get('oil', 0))}")
    else:
        return "🚨 لو رفت!"


