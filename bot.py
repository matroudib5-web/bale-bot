def parse_game_date(date_str):
    try:
        return datetime.strptime(date_str, "%Y-%m-%d")
    except Exception:
        return datetime(1939, 9, 1)


def format_game_date(dt):
    months_fa = ["ژانویه", "فوریه", "مارس", "آپریل", "مه", "ژوئن",
                 "ژوئیه", "اوت", "سپتامبر", "اکتبر", "نوامبر", "دسامبر"]
    return f"{dt.day} {months_fa[dt.month-1]} {dt.year}"


def advance_game_date(date_str, days=GAME_DAYS_PER_TURN):
    dt = parse_game_date(date_str)
    return (dt + timedelta(days=days)).strftime("%Y-%m-%d")


def get_events_for_date(date_str):
    return HISTORIC_EVENTS.get(date_str)


def fmt(n):
    try:
        if isinstance(n, float):
            return f"{int(n):,}"
        return f"{n:,}"
    except Exception:
        return str(n)


