def process_protest(user_id, state):
    """اگه اعتراض فعال داره، پردازش کن"""
    active = state.get("protest_active", 0)
    turns_left = state.get("protest_turns_left", 0)

    if active:
        turns_left -= 1
        if turns_left <= 0:
            return {
                "ended": True,
                "speech": None,
                "updates": {
                    "protest_active": 0,
                    "protest_turns_left": 0,
                    "protest_speech_done": 0,
                    "happiness": min(100, state.get("happiness", 70) + 5),
                }
            }
        return {
            "ended": False,
            "updates": {"protest_turns_left": turns_left}
        }

    # شانس شروع اعتراض
    happiness = state.get("happiness", 70)
    if happiness >= 15:
        return {"ended": False, "updates": {}}

    # زیر ۱۵ → شانس
    chance = 0.30 + (15 - happiness) * 0.05
    if random.random() < chance:
        # اعتراض شروع شد
        c = COUNTRIES[state["country"]]
        speech = f"رئیس‌جمهور {c['name']} در سخنرانی امروز خود معترضان را وطن‌فروش خواند."
        return {
            "started": True,
            "speech": speech,
            "updates": {
                "protest_active": 1,
                "protest_turns_left": 3,
                "protest_speech_done": 1,
            }
        }
    return {"ended": False, "updates": {}}


