FACTORY_PRODUCTS = {
    "steel_mill":    {"res": "steel",  "per_worker": 0.05},
    "coal_mine":     {"res": "coal",   "per_worker": 0.06},
    "refinery":      {"res": "oil",    "per_worker": 0.03},
    "food_processing": {"res": "food", "per_worker": 0.08},
    "water_treatment": {"res": "water","per_worker": 0.10},
    "ammo_factory":  {"res": "equipments", "per_worker": 0.04},
}

def process_factories(user_id, state):
    """تولید کارخونه‌ها + حقوق کارگرها"""
    factories = get_factories(user_id)
    happiness = state.get("happiness", 70)

    total_salary = 0
    production = {"steel": 0, "coal": 0, "oil": 0, "food": 0, "water": 0, "equipments": 0}

    for f in factories:
        if not f["active"]:
            continue
        key = f["factory_key"]
        workers = f["workers"]
        level = f["level"]

        # حقوق
        total_salary += workers * WORKER_SALARY

        # تولید
        if key in FACTORY_PRODUCTS:
            base = FACTORY_PRODUCTS[key]["per_worker"]
            res = FACTORY_PRODUCTS[key]["res"]
            mult = 1.0 + (level - 1) * 0.5
            # کارگرها با رضایت کم کار می‌کنن ولی فرار نمی‌کنن
            work_factor = 0.5 + (happiness / 200)  # 0.5 تا 1.0
            production[res] += workers * base * mult * work_factor

    return total_salary, production


