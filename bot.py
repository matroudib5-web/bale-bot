def compute_army_power(user_id, mode="attack"):
    """قدرت حمله یا دفاع"""
    state = get_state(user_id)
    if not state:
        return 0

    units = get_army(user_id)
    crew = get_crew(user_id)
    equip = get_equipment(user_id)

    base = 0
    for u in units:
        cat = u["category"]
        cnt = u["count"]
        power = u["power"]

        if cat == "tanks":
            crew_needed = cnt * u["crew_per_unit"]
            crew_have = crew.get("crew_tank", 0)
            crew_ratio = min(1.0, crew_have / max(1, crew_needed))
            base += cnt * power * crew_ratio
        elif cat in ("fighters", "jets"):
            crew_needed = cnt * u["crew_per_unit"]
            crew_have = crew.get("crew_pilot", 0)
            crew_ratio = min(1.0, crew_have / max(1, crew_needed))
            base += cnt * power * crew_ratio
        elif cat in ("ships",):
            crew_needed = cnt * u["crew_per_unit"]
            crew_have = crew.get("crew_ship", 0)
            crew_ratio = min(1.0, crew_have / max(1, crew_needed))
            base += cnt * power * crew_ratio
        else:
            base += cnt * power

    # سربازها
    soldiers = state.get("soldiers", 0)
    if soldiers:
        # هر ۵ سرباز یک بسته تجهیزات سبک
        needed_eq = soldiers // 5
        eq_ratio = min(1.0, equip.get("eq_light", 0) / max(1, needed_eq))
        base += soldiers * 6 * eq_ratio

    # ضریب دکمه حمله یا دفاع
    if mode == "attack":
        base = int(base * 1.0)
    else:
        base = int(base * 1.2)

    # اثر پروژه‌ها
    completed = get_completed_projects(user_id)
    for p_key in completed:
        p = PROJECTS.get(p_key, {})
        eff = p.get("effect", "")
        val = p.get("value", 0)
        if mode == "attack" and eff == "attack_bonus":
            base = int(base * (1 + val / 100))
        elif mode == "defense" and eff == "defense_bonus":
            base = int(base * (1 + val / 100))

    # نفت صفر → افت
    if state.get("oil", 0) <= 0:
        base = int(base * 0.5)

    # VIP ×۲
    if is_vip(user_id):
        base *= 2

    return base


